EXPLAIN_RULES = ('Explain this step in your next message, in 2 to 4 short numbered steps, from the smallest idea up, with one concrete case. Answer what the learner does not get. '
                 'If `simpler` is true, use simpler steps, one point each. Quote only the `quote`, with its link; if `ungrounded` is true, say so and quote nothing. '
                 'Do not say that the learner answered anything wrong, and do not give the answer to a check. Do not end with a question.')

def explain_here(
    lr:Learning,    # the learner's store
    jid:str,        # the walk the learner sees
    i:int,          # the step the learner sees
    note:str,       # what the learner does not get, in their words
    settings:dict|None=None,  # the host's values of the settings rows, for this call only
    revision=None,  # the `revision` of the walk that the caller last saw; another value gives `stale_state`
) -> dict:
    "The data to teach step `i` of walk `jid` to a learner who does not get it, and the rules for the explanation; the agent writes it. It keeps what confuses the learner. It calls no model."
    def go():
        j, bad = _open(lr, jid, revision)
        if bad: return bad
        if not (type(i) is int and 0 <= i < len(j.steps)): return failed('not_found', f'no step {i} in walk {jid!r}', walk=jid, step=i)
        line = show.clean_note(note)
        if not line: raise ValueError('say what you do not get')
        s = j.steps[i]; c = lr.concept(s['slug']); q = _quote(s); name = (c or {}).get('name') or s['slug']
        miss = [n.name for n in path.walk_needs(lr, j, i) if n.state in ('missing', 'shaky')]
        g = _gauge(c) if c else dict(state='unseen', floor=0, recall=0.)
        kept = note_confusion(lr, jid, i, line)
        if kept['status'] != 'ok': return kept
        return result('ok', walk=jid, step=i, vault=_vault(lr), revision=kept['revision'],
                      data=dict(concept=s['slug'], name=name, statement=(c or {}).get('statement', ''), core=(c or {}).get('core', ''), quote=q, ungrounded=q is None, gauge=g,
                                level=lr.level_of(c, miss) if c else '', simpler=bool(miss) or g['state'] in ('unseen', 'gap', 'weak'), needs=miss, confusion=line,
                                rules=EXPLAIN_RULES, recorded=kept['data']['recorded'], confuses=kept['data']['confuses']))
    with learner.use_settings(settings): return _run(go, walk=jid, step=i)


class ModelRefused(Exception):
    "What a host `ask` raises when the model declines to answer."

class _Stopped(BaseException):
    "Ends an operation at a safe point."

def vault_failure(e:BaseException) -> str|None:
    "`'read_only'` or `'vault_locked'` when `e` is a failed write to the vault, else None."
    s = ' '.join([*(c.__name__ for c in type(e).__mro__), str(e)]).lower()
    return 'read_only' if 'readonly' in s else 'vault_locked' if re.search(r'\b(?:busy|locked)', s) else None

def _run(f, **at) -> dict:
    "The result of `f()`; `at` (`walk`, `step`) goes on a failure."
    try: return f()
    except _Stopped: return failed('stopped', 'stopped before anything was saved', **at)
    except Withheld as e: return failed('privacy_refused', str(e), **at)
    except (ModelRefused, ValueError) as e: return failed('model_refused', str(e), **at)
    except Exception as e:
        if (k := vault_failure(e)): return failed(k, str(e), **at)
        raise

def _stoppable(ask, stopping):
    "`ask` that checks `stopping()` before the call and after it, so before its answer is used."
    def f(prompt, sp=''):
        if stopping(): raise _Stopped()
        out = ask(prompt, sp)
        if stopping(): raise _Stopped()
        return out
    return f

def _vault(lr:Learning) -> str: return Path(str(lr.v.path)).name


RULE = 'Sources: quote only the text that a step shows as its quote, with its link. A step marked ungrounded has no source. Say so, and never invent a quote.'

def learner_context(
    lr:Learning,   # the learner's store
    jid:str=None,  # the open walk, if any
    i:int=None,    # the open step; the current step when None
    n:int=1200     # the most characters
) -> str:
    "A short plain-text block for a system prompt: the open walk and step, its gauge, and the rule for sources."
    r = walk_state(lr, jid) if jid else None
    if not r or r['status'] != 'ok': return clip(f'Learn mode. No walk is open.\n{RULE}', n)
    d = r['data']; k = d['current'] if i is None else i
    head = f"Learn mode. Walk: {d['title']} ({jid})."
    if k is None or not 0 <= k < len(d['steps']): body = [head, 'No step is open.']
    else:
        s = d['steps'][k]; g = d['gauge'].get(s['slug'], {})
        body = [f"{head} Step {k + 1} of {len(d['steps'])}: {s['name']}. {s['statement']}",
                f"Status: {s['status']}. Understanding: {g.get('state', 'unseen')}, depth {g.get('floor', 0)}, recall {g.get('recall', 0):.0%}.",
                f"Source: \"{clip(q['text'], 300)}\" ({q['title']}, {q['url']})" if (q := s['quote']) else 'Source: none. This step is ungrounded.',
                *([f"Check: {s['check']['question']}"] if s['check'] and s['check']['question'] else [])]
    return clip('\n'.join([RULE, *body]), n)

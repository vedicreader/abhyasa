WORDS_MOST = 400   # the most characters of the words of the learner that go to the planner

def change_walk(
    lr:Learning,                         # the learner's store
    ask,                                 # the host model call, `ask(prompt, sp='')`
    jid:str,                             # the walk id
    instruction:str,                     # what the learner wants to change, in their words
    stopping=lambda: False,              # true after a stop
    settings:dict|None=None,             # the host's values of the settings rows, for this call only
    revision=None,                       # the `revision` of the walk that the caller last saw; another value gives `stale_state`
) -> dict:
    "Change walk `jid` from the words of the learner, as one change with an Undo."
    def go():
        j, bad = _open(lr, jid, revision)
        if bad: return bad
        words = ' '.join(path.CTRL.sub('', str(instruction or '')).split())[:WORDS_MOST]
        if not words: raise ValueError('say what should change')
        ask_ = _stoppable(ask, stopping)
        weak = [s['slug'] for s in j.steps if (o := (s.get('done') or {}).get('outcome')) and o not in ('solid', 'skipped')]
        cs = path.propose(ask_, j, {c.slug: c.name for c in lr.concepts()}, words, weak)
        if not cs: return _changed(lr, jid, j, None, changes=[], sources_wanted=[], message='the tutor found nothing to change')
        if (cur := lr.journey(jid)) is None or cur.get('updated') != j.get('updated'): return _stale(lr, jid, cur or j)
        j2, rows = path.improve_walk(lr, ask_, jid, cs, [VaultSource(lr)])
        return _changed(lr, jid, j2, rows, changes=[dict(op=c.op, idea=c.slug, name=c.name, why=c.why) for c in cs], sources_wanted=[c.slug for c in cs if c.op == 'source'])
    with learner.keyed_lock('agent-edit', jid), learner.use_settings(settings): return _run(_kept(go, walk=jid), walk=jid)


def _stale(lr:Learning, jid:str, j, i:int=None) -> dict:
    "The `stale_state` result for walk `j`: it carries the current revision."
    cur = j.get('updated')
    return result('error', error='stale_state', walk=jid, step=i, vault=_vault(lr), revision=cur, data=dict(message='the walk changed since this revision', revision=cur))

def _open(lr:Learning, jid:str, revision=None):
    "`(walk, None)`, or `(None, failure)`: `not_found`, or `stale_state` when `revision` is not the `updated` time of the walk."
    j = lr.journey(jid)
    if j is None or j.get('mode') != 'walk': return None, failed('not_found', f'no walk {jid!r}', walk=jid)
    return (None, _stale(lr, jid, j)) if revision is not None and revision != j.get('updated') else (j, None)

def _idea(j, idea) -> str|None:
    "The slug that `idea` names in walk `j`: a slug, or the number of the idea from 1; None when there is none."
    ss, x = [s['slug'] for s in j.steps], str(idea).strip()
    return x if x in ss else ss[int(x) - 1] if x.isdecimal() and 0 < int(x) <= len(ss) else None

def _changed(lr:Learning, jid:str, j, rows, **data) -> dict:
    "The `ok` result of a change; `rows` is the history from `edit_walk`, None when nothing changed."
    return result('ok', walk=jid, vault=_vault(lr), revision=j.get('updated'),
                  data=dict(changed=rows is not None, change=rows[0].id if rows else '', ideas=[s['slug'] for s in j.steps], **data))

def _kept(go, **at):
    "`go` with a `KeyError` of the walk editor (the walk or an idea left) as `not_found`."
    def f():
        try: return go()
        except KeyError as e: return failed('not_found', str(e.args[0] if e.args else 'not found'), **at)
    return f

def _hand(lr:Learning, jid:str, idea, make, revision=None) -> dict:
    "One change by hand to the idea `idea` of walk `jid`; `make(slug, name)` gives `(op, what, touch)` for `edit_walk`."
    def go():
        j, bad = _open(lr, jid, revision)
        if bad: return bad
        if (slug := _idea(j, idea)) is None: return failed('not_found', f'no idea {idea!r} in walk {jid!r}', walk=jid)
        op, what, touch = make(slug, (lr.concept(slug) or {}).get('name') or slug)
        j2, rows = path.edit_walk(lr, jid, op, what, touch=touch)
        return _changed(lr, jid, j2, rows)
    with learner.keyed_lock('agent-edit', jid): return _run(_kept(go, walk=jid), walk=jid)

def keep_idea(lr:Learning, jid:str, idea:str, revision=None) -> dict:
    "Keep the idea: the builder and the box of the walk do not change it. It is one change, with an Undo."
    return _hand(lr, jid, idea, lambda s, n: (lambda ss: path.lock_step(ss, s), f'Kept “{n}”. The builder and the box do not change it.', None), revision)

def drop_idea(lr:Learning, jid:str, idea:str, revision=None) -> dict:
    "Remove the idea from the walk. It is one change, with an Undo."
    return _hand(lr, jid, idea, lambda s, n: (lambda ss: path.remove_step(ss, s), f'Removed “{n}”.', s), revision)

def move_idea(lr:Learning, jid:str, idea:str, to:int, revision=None) -> dict:
    "Move the idea to the place `to`, from 1. It is one change, with an Undo."
    return _hand(lr, jid, idea, lambda s, n: (lambda ss: path.move_step(ss, s, to - 1 if type(to) is int else to), f'Moved “{n}” to idea {to}.', s), revision)


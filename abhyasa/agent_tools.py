def _gauge(c) -> dict:
    "What the engine knows of concept `c`: its state, its depth and its recall."
    u = learner.understanding(c)
    return dict(state=u.state, floor=u.floor, recall=round(u.recall, 2))

def _quote(s) -> dict|None:
    "The stored passage of step `s` with its link, or None when it has no text or no link."
    r = s.get('read') or {}
    return dict(text=r['text'], url=r['url'], title=r.get('title') or '') if (r.get('text') or '').strip() and r.get('url') else None

def _asked(lr:Learning, s) -> str:
    "The question of the check of step `s`: the open question, else the question of the plan, else ''."
    m = lr.open_q(s.get('qid') or '')
    return m.q.get('question', '') if m and m.status == 'open' else ' '.join(str((s.get('check') or {}).get('q') or '').split())

def _step(lr:Learning, i:int, s, c) -> dict:
    "Step `i` of a walk, as `walk_state` gives it; `s` has its `dot`, and `c` is its concept."
    q = _quote(s)
    return dict(i=i, slug=s['slug'], name=(c or {}).get('name') or s['slug'], statement=(c or {}).get('statement', ''), status=s.dot,
                quote=q, ungrounded=q is None,
                check=None if s.dot in ('done', 'skipped', 'known') else dict(question=_asked(lr, s), kind=(s.get('check') or {}).get('kind', 'short')))

def walk_state(
    lr:Learning,  # the learner's store
    jid:str,      # the walk id
    settings:dict|None=None   # the host's values of the settings rows, for this call only; None reads the settings file
) -> dict:
    "The walk as plain data: its steps with their quote or `ungrounded` and their checks, and the gauge of each concept."
    def get():
        j = lr.journey(jid)
        if j is None or j.get('mode') != 'walk': return failed('not_found', f'no walk {jid!r}', walk=jid)
        by = {c.slug: c for c in lr.concepts()}
        ws = learner.walk_state(j, by)
        steps = [_step(lr, i, s, by.get(s['slug'])) for i, s in enumerate(ws.steps)]
        return result('ok', walk=jid, vault=_vault(lr), revision=j.get('updated'),
                      data=dict(id=jid, title=j.title, steps=steps, current=ws.current, gauge={s['slug']: _gauge(by[s['slug']]) for s in steps if s['slug'] in by}))
    with learner.use_settings(settings): return _run(get, walk=jid)


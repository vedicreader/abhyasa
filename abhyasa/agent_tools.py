def list_versions(lr:Learning, jid:str) -> dict:
    "The earlier versions of walk `jid`, newest first; number 1 is the newest."
    def go():
        j, bad = _open(lr, jid)
        if bad: return bad
        return result('ok', walk=jid, vault=_vault(lr), revision=j.get('updated'),
                      data=dict(versions=[dict(version=k, id=e.id, what=e.what, who=e.who, at=e.at, restorable=e.before is not None) for k, e in enumerate(lr.edits('walk', jid), 1)]))
    return _run(go, walk=jid)

def restore_version(lr:Learning, jid:str, version:int, revision=None) -> dict:
    "Go back to the version of walk `jid` before the change `version` of `list_versions`, as a new change with an Undo."
    def go():
        j, bad = _open(lr, jid, revision)
        if bad: return bad
        es = lr.edits('walk', jid)
        if not (type(version) is int and 0 < version <= len(es)): return failed('not_found', f'no version {version!r} in walk {jid!r}', walk=jid)
        j2, rows = path.restore_walk(lr, jid, es[version - 1].id)
        return _changed(lr, jid, j2, rows, restored=es[version - 1].what)
    with learner.keyed_lock('agent-edit', jid): return _run(_kept(go, walk=jid), walk=jid)


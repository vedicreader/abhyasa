CHIPS = ('gh', 'folder', 'repo', 'file', 'link', 'vault', 'doc')

def _chip(source) -> str:
    "The chip id of `source`: a link, a path to a file or a folder, a chip id as it is, or else the name of a vault source."
    s = ' '.join(str(source or '').split())
    if re.match(r'https?://', s): return f'link:{s}'
    if s.partition(':')[0] in CHIPS and ':' in s: return s
    p = Path(s).expanduser() if s else None
    return f'folder:{p.resolve()}' if p and p.is_dir() else f'file:{p.resolve()}' if p and p.is_file() else f'vault:{s}' if s else ''


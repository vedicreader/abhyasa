RULE = 'Sources: quote only the text that a step shows as its quote, with its link. A step marked ungrounded has no source. Say so, and never invent a quote.'

def page_of(page:str) -> dict:
    "The Abhyasa page at the path `page` as `dict(kind, jid, i, slug)`; `kind` is step, walk, concept, you, graph, library, talk, today or other, and '' for no path."
    if not str(page or '').strip(): return dict(kind='', jid=None, i=None, slug=None)
    p = unquote(urlsplit(str(page)).path).removeprefix('/learn/abh').rstrip('/') or '/'
    if m := re.fullmatch(r'/w/([^/]+)(?:/(\d+))?(?:/.*)?', p): return dict(kind='step' if m[2] else 'walk', jid=m[1], i=int(m[2]) if m[2] else None, slug=None)
    if m := re.fullmatch(r'/c/([^/]+)(?:/.*)?', p): return dict(kind='concept', jid=None, i=None, slug=m[1])
    k = 'you' if re.match(r'/you(/|$)', p) else 'graph' if p in ('/graph', '/library/graph') else 'library' if re.match(r'/(library|concepts)(/|$)', p) else 'talk' if re.match(r'/(t|talk|talks)(/|$)', p) else 'today' if p in ('/', '/today') else 'other'
    return dict(kind=k, jid=None, i=None, slug=None)

def _on_screen(lr:Learning, pg:dict) -> str:
    "The line that says what the Learn tab shows, for a page that is no walk step; '' for a walk or a step."
    k, c = pg['kind'], lr.concept(pg['slug']) if pg['slug'] else None
    if not k or k in ('step', 'walk'): return ''
    return f"On screen: the concept {c['name']}. {c.get('statement', '')} Understanding: {_gauge(c)['state']}." if k == 'concept' and c else f'On screen: the {k} page of Learn.'

def learner_context(
    lr:Learning,   # the learner's store
    jid:str=None,  # the open walk, if any
    i:int=None,    # the open step; the current step when None
    n:int=1200,    # the most characters
    page:str=None  # the path that the Learn tab shows; the walk and step of the page win over `jid` and `i`
) -> str:
    "A short plain-text block for a system prompt: what is on screen, the open walk and step, its gauge, and the rule for sources."
    pg = page_of(page)
    if pg['kind'] in ('step', 'walk'): jid, i = pg['jid'], pg['i']
    r = walk_state(lr, jid) if jid else None
    if not r or r['status'] != 'ok': return clip('\n'.join(['Learn mode. No walk is open.', RULE, *filter(None, [_on_screen(lr, pg)])]), n)
    d = r['data']; k = d['current'] if i is None else i
    head = f"Learn mode. Walk: {d['title']} ({jid})."
    if k is None or not 0 <= k < len(d['steps']): body = [head, 'No step is open.']
    else:
        s = d['steps'][k]; g = d['gauge'].get(s['slug'], {})
        body = [f"{head} Step {k + 1} of {len(d['steps'])}: {s['name']}. {s['statement']}",
                f"Status: {s['status']}. Understanding: {g.get('state', 'unseen')}, depth {g.get('floor', 0)}, recall {g.get('recall', 0):.0%}.",
                f"Source: \"{clip(q['text'], 300)}\" ({q['title']}, {q['url']})" if (q := s['quote']) else 'Source: none. This step is ungrounded.',
                *([f"Check: {s['check']['question']}"] if s['check'] and s['check']['question'] else [])]
    on = ["On screen: this step. When the learner says they do not get it, it is about this step: call explain_here."] if pg['kind'] == 'step' else ['On screen: this walk.'] if pg['kind'] == 'walk' else []
    return clip('\n'.join([RULE, *on, *body]), n)

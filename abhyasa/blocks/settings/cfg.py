class Routes:
    base = '/settings'
    value = '/settings/value'          # save one value of the settings table
    default = '/settings/default'      # use the default of one value
    group_ask = '/settings/group/ask'  # ask before a group goes back to its defaults
    group_default = '/settings/group/default'   # use the defaults of a group
    use = '/settings/use'            # switch the speech engine and model
    search = '/settings/search'      # look up speech models on Hugging Face
    get = '/settings/get'            # download a model in the background, then use it
    jobs = '/settings/jobs'          # the download progress lines
    status = '/settings/status'      # the state of the model in use
    remove = '/settings/remove'      # delete a model that this page downloaded
    key = '/settings/key'            # set or clear the OpenAI key
    model = '/settings/model'        # the model for one tutor task
    test = '/settings/model/test'    # time one short call to a model
    catalog = '/settings/catalog'    # the models that can run here, for the pickers
    look = '/settings/look'          # the theme and the mode: light, dark or auto
    prompt = '/settings/prompt'      # save the text of one tutor prompt; empty: the default
    prompt_default = '/settings/prompt/default'   # use the default text of one tutor prompt
    out = '/settings/voice'              # the speaking voice: the engine, the model and the voice
    out_get = '/settings/voice/get'      # download a voice model in the background, then use it
    out_search = '/settings/voice/search'   # look up text to speech models on Hugging Face
    out_sample = '/settings/voice/sample'   # say one sample line in the voice of the settings: JSON with base64 WAV
    out_status = '/settings/voice/status'   # the state of the voice model in use
